/**
 * Generates dist/sw.js with a precache list built from the REAL bundle.
 *
 * Why this exists: a hand-written precache list cannot name content-hashed
 * chunks (`/assets/index-Cv2_Ti6G.js`), so the app shell would cache while the
 * JS that powers it did not. Offline, index.html then loaded and immediately
 * failed to fetch its own bundle — the app looked like a dead webpage.
 *
 * Rules the generated worker follows:
 *  - Precache index.html, every emitted asset, and the listed static files at
 *    install time, so a single online visit is enough to go fully offline.
 *  - Hashed assets are cache-first and immutable (the filename IS the version).
 *  - Navigations are network-first with a cached-index.html fallback.
 *  - respondWith is NEVER handed undefined; every path ends in a real Response.
 */

const STATIC_EXTRAS = [
  '/manifest.json',
  '/favicon.png',
  '/favicon.svg',
  '/apple-touch-icon.png',
  '/icon-192.png',
  '/icon-512.png',
  '/icons.svg',
  '/splash-logo.png',
];

export function offlineServiceWorker({ cacheName = 'tripreport' } = {}) {
  return {
    name: 'offline-service-worker',
    apply: 'build',

    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle)
        .map((key) => `/${bundle[key].fileName}`)
        // index.html is precached explicitly; large map packs are opt-in
        // downloads handled by the offline-maps feature, not the app shell.
        .filter((p) => p !== '/index.html' && !p.startsWith('/maps/'))
        .sort();

      const precache = ['/index.html', ...assets, ...STATIC_EXTRAS];
      // Cache name includes a build fingerprint so a new deploy replaces the
      // old cache wholesale instead of serving a half-updated mix.
      const version = fingerprint(assets);

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: renderServiceWorker({
          cacheName: `${cacheName}-${version}`,
          precache,
        }),
      });
    },
  };
}

function fingerprint(assets) {
  let hash = 0;
  const joined = assets.join('|');
  for (let i = 0; i < joined.length; i += 1) {
    hash = (Math.imul(31, hash) + joined.charCodeAt(i)) | 0;
  }
  return Math.abs(hash).toString(36);
}

function renderServiceWorker({ cacheName, precache }) {
  return `// AUTO-GENERATED by vite-plugin-offline-sw.js — do not edit by hand.
const CACHE = '${cacheName}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

// Fully offline-capable install: if any single file fails the whole install
// fails, so we add them individually and tolerate misses on optional extras.
self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(PRECACHE.map(async (url) => {
      try {
        // cache: 'reload' bypasses the HTTP cache so we store fresh copies.
        const res = await fetch(new Request(url, { cache: 'reload' }));
        if (res.ok) await cache.put(url, res);
      } catch {
        // A missing optional icon must not break offline support.
      }
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(
      keys.filter((k) => k !== CACHE && k.startsWith('tripreport')).map((k) => caches.delete(k)),
    );
    await self.clients.claim();
  })());
});

self.addEventListener('message', (e) => {
  if (e.data === 'SKIP_WAITING') self.skipWaiting();
});

const OFFLINE_FALLBACK = new Response(
  '<!doctype html><meta charset="utf-8"><title>TripReport offline</title>'
  + '<body style="font-family:system-ui;padding:24px;color:#1A1917;background:#F5F4F0">'
  + '<h1 style="font-size:18px">TripReport is not fully installed yet</h1>'
  + '<p style="font-size:14px;color:#6B6763;line-height:1.5">Reconnect once so the app can finish caching itself, '
  + 'then it will open without service.</p></body>',
  { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } },
);

self.addEventListener('fetch', (e) => {
  const { request } = e;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Navigations: serve the cached shell first so launching offline is instant
  // and never depends on a network round trip.
  if (request.mode === 'navigate') {
    e.respondWith((async () => {
      const cached = await caches.match('/index.html');
      if (cached) {
        // Refresh the shell in the background for the next launch.
        e.waitUntil((async () => {
          try {
            const res = await fetch(request);
            if (res.ok) (await caches.open(CACHE)).put('/index.html', res.clone());
          } catch { /* offline is fine */ }
        })());
        return cached;
      }
      try {
        const res = await fetch(request);
        if (res.ok) (await caches.open(CACHE)).put('/index.html', res.clone());
        return res;
      } catch {
        return OFFLINE_FALLBACK;
      }
    })());
    return;
  }

  // Hashed build assets are immutable: cache-first, and cache on first sight.
  if (url.pathname.startsWith('/assets/')) {
    e.respondWith((async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      try {
        const res = await fetch(request);
        if (res.ok) (await caches.open(CACHE)).put(request, res.clone());
        return res;
      } catch {
        // Never hand respondWith undefined — that surfaces as a network error.
        return new Response('', { status: 504, statusText: 'Offline and not cached' });
      }
    })());
    return;
  }

  // Offline map packs: cache-first, but never block on them.
  if (url.pathname.startsWith('/maps/')) {
    e.respondWith((async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      try {
        return await fetch(request);
      } catch {
        return new Response('', { status: 504, statusText: 'Map pack unavailable offline' });
      }
    })());
    return;
  }

  // Everything else same-origin: cache-first with a network fill.
  e.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const res = await fetch(request);
      if (res.ok) (await caches.open(CACHE)).put(request, res.clone());
      return res;
    } catch {
      return new Response('', { status: 504, statusText: 'Offline and not cached' });
    }
  })());
});
`;
}
